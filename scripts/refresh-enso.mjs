#!/usr/bin/env node
/**
 * Regenerates src/features/conditions/enso/enso-data.generated.ts from NOAA CPC (ADR 012).
 *
 *   node scripts/refresh-enso.mjs
 *
 * Run monthly after CPC's ENSO Diagnostic Discussion (2nd Thursday). Sources:
 *   history  https://www.cpc.ncep.noaa.gov/data/indices/oni.ascii.txt           (ONI v5)
 *   outlook  https://www.cpc.ncep.noaa.gov/products/analysis_monitoring/enso/roni/probabilities/
 * Review the diff: the outlook is parsed from CPC's HTML table and the script refuses to
 * write if it does not find exactly 9 seasons.
 */
import { writeFileSync } from "node:fs";

const ONI_URL = "https://www.cpc.ncep.noaa.gov/data/indices/oni.ascii.txt";
const OUTLOOK_URL = "https://www.cpc.ncep.noaa.gov/products/analysis_monitoring/enso/roni/probabilities/";
const OUT = new URL("../src/features/conditions/enso/enso-data.generated.ts", import.meta.url);

const SEASONS = ["DJF", "JFM", "FMA", "MAM", "AMJ", "MJJ", "JJA", "JAS", "ASO", "SON", "OND", "NDJ"];

const oniText = await (await fetch(ONI_URL)).text();
const oni = [];
for (const line of oniText.split("\n").slice(1)) {
  const [seas, yr, , anom] = line.trim().split(/\s+/);
  const i = SEASONS.indexOf(seas);
  if (i === -1 || !yr || anom === undefined) continue;
  // Attribute the 3-month season to its centre month (DJF -> January of YR).
  oni.push([Number(yr), i + 1, Number(anom)]);
}
if (oni.length < 900) throw new Error(`ONI parse looks wrong: ${oni.length} seasons`);

const html = await (await fetch(OUTLOOK_URL)).text();
const text = html.replace(/<[^>]+>/g, " ").replace(/&[a-z]+;/g, " ").replace(/\s+/g, " ");
const issued = /Issued ([A-Z][a-z]+ \d{4})/.exec(text)?.[1];
const outlook = [];
const re = /\b(DJF|JFM|FMA|MAM|AMJ|MJJ|JJA|JAS|ASO|SON|OND|NDJ) [A-Z][a-z]{2} [A-Z][a-z]{2} [A-Z][a-z]{2} (\d{1,3}) (\d{1,3}) (\d{1,3})\b/g;
for (const m of text.matchAll(re)) outlook.push([m[1], Number(m[2]), Number(m[3]), Number(m[4])]);
if (!issued || outlook.length !== 9) throw new Error(`Outlook parse looks wrong: issued=${issued} seasons=${outlook.length}`);

const [lastYr, lastMonth] = oni.at(-1);
writeFileSync(
  OUT,
  `// GENERATED by scripts/refresh-enso.mjs on ${new Date().toISOString().slice(0, 10)} — do not edit by hand.
// History: CPC ONI v5 (${ONI_URL})
// Outlook: CPC Official ENSO Probabilities, issued ${issued} (${OUTLOOK_URL})

/** [year, centre month 1–12, ONI anomaly °C] */
export const ONI_HISTORY: readonly (readonly [number, number, number])[] = ${JSON.stringify(oni)};

/** The last observed season's centre month — the outlook starts after it. */
export const ONI_LAST = { year: ${lastYr}, month: ${lastMonth} } as const;

export const OUTLOOK_ISSUED = ${JSON.stringify(issued)};
export const RETRIEVED = ${JSON.stringify(new Date().toISOString().slice(0, 10))};
export const ONI_SOURCE_URL = ${JSON.stringify(ONI_URL)};
export const OUTLOOK_SOURCE_URL = ${JSON.stringify(OUTLOOK_URL)};

/** [season, P(La Niña) %, P(Neutral) %, P(El Niño) %], in order; each is placed on its season's centre month (SON → October), which may leave a gap after ONI_LAST. */
export const OUTLOOK: readonly (readonly [string, number, number, number])[] = ${JSON.stringify(outlook)};
`,
);
console.log(`ONI ${oni.length} seasons to ${lastYr}-${lastMonth}; outlook issued ${issued}: ${outlook.map((o) => o[0]).join(" ")}`);
